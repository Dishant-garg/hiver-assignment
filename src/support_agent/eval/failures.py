"""Failure analysis. Reads results/ and the golden set and writes results/failures.md.

Read-only over the artifacts of `eval.run`: it makes no LLM calls and recomputes no metric, so it
can be re-run any time without a key. Run with `python -m support_agent.eval.failures`.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

from .. import config

MAX_EXAMPLES = 3       # per (true, pred) intent confusion pair
MAX_LOW_JUDGED = 12    # lowest-scored agent replies shown in full


def _clip(text: object, n: int = 260) -> str:
    s = " ".join(str("" if text is None else text).split())
    return s if len(s) <= n else s[: n - 1] + "…"


def load(results_dir: Path | None = None) -> pd.DataFrame:
    """Join predictions, golden labels and the agent's judge scores on golden_id.

    A directory written with `--skip-judge` has no `judge_scores.csv`, and one written with
    `--limit` has only some of the golden rows. Both are usable here: the judge columns are
    simply absent, section D says so, and the rest of the report is unaffected.
    """
    rd = results_dir or config.RESULTS_DIR
    preds = pd.read_csv(rd / "predictions.csv")
    golden = pd.read_csv(config.GOLDEN_DIR / "golden_set.csv")
    df = preds.merge(golden, on="golden_id", how="inner", validate="one_to_one", suffixes=("", "_gold"))
    judge_path = rd / "judge_scores.csv"
    if not judge_path.exists():
        print(f"warning: no {judge_path.name} in {rd}; judge sections of the report will be empty "
              f"(a --skip-judge run writes no judge scores)", file=sys.stderr)
        return df
    judge = pd.read_csv(judge_path)
    judge = judge[judge["system"] == "agent"].drop(columns=["system", "candidate"])
    return df.merge(judge, on="golden_id", how="left", validate="one_to_one")


def _case(row: pd.Series, *, reply: bool = True, evidence: bool = False) -> list[str]:
    out = [f"**golden {int(row.golden_id)}** (true intent `{row.intent}`, agent said `{row.agent_intent}`, "
           f"confidence {row.agent_confidence:.2f}, top retrieval score {row.agent_top_score:.3f})",
           "",
           f"- Customer: {_clip(row.customer_text)}",
           f"- Golden label: should_escalate `{bool(row.should_escalate)}`, reason `{row.escalation_reason}`",
           f"- Golden note: {_clip(row.notes, 220)}"]
    if reply:
        out.append(f"- Agent reply: {_clip(row.agent_reply)}")
    out.append(f"- Agent decision: escalate `{bool(row.agent_escalate)}`, rules `{row.agent_rule_hits or '(none)'}`, "
               f"llm_escalate `{bool(row.agent_llm_escalate)}`, reason: {_clip(row.agent_reason, 160)}")
    if pd.notna(row.get("overall")):
        out.append(f"- Judge: overall {int(row.overall)}, grounded {int(row.groundedness)}, "
                   f"correct {int(row.correctness)}, actionable {int(row.actionability)} — {_clip(row.rationale, 200)}")
    if evidence:
        out.append(f"- Evidence retrieved: {_clip(row.agent_evidence, 320)}")
    out.append("")
    return out


def build(df: pd.DataFrame) -> str:
    truth, pred = df["should_escalate"].astype(bool), df["agent_escalate"].astype(bool)
    L: list[str] = ["# Agent failure cases",
                    "",
                    f"Generated by `python -m support_agent.eval.failures` from `results/predictions.csv`, "
                    f"`results/judge_scores.csv` and `data/golden/golden_set.csv`. n = {len(df)}.",
                    ""]

    missed = df[truth & ~pred]
    L += [f"## A. Missed escalations ({len(missed)})", "",
          "Golden says a human was needed; the agent auto-handled. The expensive error.", ""]
    for _, r in missed.iterrows():
        L += _case(r)

    unnecessary = df[~truth & pred]
    L += [f"## B. Unnecessary escalations ({len(unnecessary)})", "",
          "Golden says the agent could have answered; the agent escalated. The cheap error, but it is "
          "what caps the automation rate.", ""]
    by_rule = unnecessary["agent_rule_hits"].fillna("(none)").value_counts()
    L += ["| rule hits | count |", "|---|---:|"]
    L += [f"| `{k}` | {v} |" for k, v in by_rule.items()]
    L += ["", f"Up to {MAX_EXAMPLES} examples from each rule-hit group:", ""]
    for rules, grp in unnecessary.groupby(unnecessary["agent_rule_hits"].fillna("(none)")):
        L += [f"### `{rules}` — {len(grp)} rows", ""]
        for _, r in grp.head(MAX_EXAMPLES).iterrows():
            L += _case(r)

    wrong = df[df["agent_intent"] != df["intent"]]
    L += [f"## C. Intent confusions ({len(wrong)} of {len(df)} rows wrong)", ""]
    pairs = wrong.groupby(["intent", "agent_intent"]).size().sort_values(ascending=False)
    L += ["| true | predicted | count |", "|---|---|---:|"]
    L += [f"| `{t}` | `{p}` | {c} |" for (t, p), c in pairs.items()]
    L += ["", f"Up to {MAX_EXAMPLES} examples for every pair with 2 or more rows:", ""]
    for (t, p), c in pairs.items():
        if c < 2:
            continue
        L += [f"### true `{t}` → predicted `{p}` ({c})", ""]
        grp = wrong[(wrong["intent"] == t) & (wrong["agent_intent"] == p)]
        for _, r in grp.head(MAX_EXAMPLES).iterrows():
            L += _case(r, reply=False)

    if "overall" not in df.columns:
        print("warning: no judge scores loaded; skipping section D", file=sys.stderr)
        L += ["## D. Lowest-judged agent replies (unavailable)", "",
              "This results directory has no `judge_scores.csv`, so there is nothing to rank. "
              "Re-run the evaluation without `--skip-judge` to fill this section in.", ""]
    else:
        low = df[df["overall"] <= 2].sort_values(["overall", "correctness", "groundedness", "golden_id"])
        L += [f"## D. Lowest-judged agent replies ({len(low)} scored overall ≤ 2, "
              f"{int((df['overall'] == 1).sum())} of them a 1)", "",
              "The judge scores replies blind and is ±1 point noisy on a single row "
              "(`docs/05-judge-agreement.md`), so read these as a pile, not as verdicts. "
              f"The {MAX_LOW_JUDGED} worst, with the evidence the reply had to work from:", ""]
        for _, r in low.head(MAX_LOW_JUDGED).iterrows():
            L += _case(r, evidence=True)

    hits = df["agent_rule_hits"].fillna("")
    flagged = df[hits.str.contains("forbidden_promise") | hits.str.contains("too_long")]
    L += [f"## E. Post-check content rules: forbidden_promise / too_long ({len(flagged)})", "",
          "These two rules read the drafted reply itself rather than the message or the retrieval score. "
          "Every hit here is a draft the agent wrote and the rules then refused to send.", ""]
    if flagged.empty:
        L += ["No rows.", ""]
    for _, r in flagged.iterrows():
        L += _case(r)

    return "\n".join(L).replace("\n\n\n", "\n\n") + "\n"


def main() -> None:
    df = load()
    out = config.RESULTS_DIR / "failures.md"
    out.write_text(build(df), encoding="utf-8")
    print(f"wrote {out} ({len(df)} rows)")


if __name__ == "__main__":
    main()
